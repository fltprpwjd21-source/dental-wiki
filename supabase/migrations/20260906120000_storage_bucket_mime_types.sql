-- 왜 필요한가
--   첨부 확정 등록이 크기·형식을 요청 본문에서 받아 그대로 믿고 있었다. 그 값을
--   보내는 쪽이 곧 제한을 피하려는 쪽이라 아무 의미가 없었다 (LESSONS §9-3).
--   애플리케이션 쪽은 이제 스토리지에 올라간 실제 값을 읽어 검사하도록 고쳤는데,
--   그것만으로는 "확정 등록을 아예 부르지 않고 서명 URL 로만 올리는" 경로가 남는다.
--   그렇게 올라간 오브젝트는 DB 행이 없어 화면에는 안 보이지만, 우리 버킷의 용량은
--   그대로 잡아먹는다.
--
--   용량은 20260905120000 에서 file_size_limit 으로 이미 물리적으로 막았다.
--   그때 형식(allowed_mime_types)은 "별도 판단"으로 미뤄뒀는데, 이 마이그레이션이
--   그 판단이다.
--
-- 무엇을 하는가
--   lib/file-rules.ts 의 ALLOWED_MIME_TYPES 와 같은 목록을 버킷에 건다.
--   목록에 없는 형식은 스토리지가 업로드 시점에 거부하므로, 앱 코드를 우회해도
--   html·svg 같은 스크립트를 품을 수 있는 파일이 버킷에 들어오지 못한다.
--
-- 주의
--   이 목록과 lib/file-rules.ts 는 손으로 맞춰야 한다. 한쪽만 늘리면 "파일 선택은
--   되는데 업로드가 실패"하거나 그 반대가 된다. 형식을 추가할 때 두 곳을 함께 고칠 것.
update storage.buckets
   set allowed_mime_types = array[
         'image/png',
         'image/jpeg',
         'image/gif',
         'image/webp',
         'application/pdf'
       ]
 where id = 'file-server';
