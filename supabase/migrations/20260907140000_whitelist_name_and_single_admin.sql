-- 화이트리스트에 이름을 붙이고, 관리자 계정을 하나로 정리한다.
--
-- 왜 이름이 필요한가
--   지금까지 설정 화면의 목록은 사원번호·관리자 여부·등록일뿐이었다. 사원번호만 보고
--   "이게 누구지"를 알 수 없어서, 퇴사자를 지우려 해도 어느 줄을 지워야 하는지 확인할
--   방법이 없었다. 관리자 여부 칸을 이름 칸으로 바꾼다.
--
-- 왜 nullable 인가
--   이미 등록된 사원번호가 있는데, 그 사람들의 이름을 여기서 지어낼 수는 없다.
--   비워둔 채로 두고 설정 화면에서 직접 채우게 한다 (이름 칸을 눌러 수정).
alter table employee_whitelist
  add column name text;

comment on column employee_whitelist.name is
  '표시용 이름. 누가 어느 사원번호인지 목록에서 알아보기 위한 값이며, 로그인·권한과는 무관하다.';

-- 관리자 계정은 00001 하나만 남긴다.
--
--   원래는 등록할 때 "관리자로 등록" 체크박스로 아무나 관리자를 만들 수 있었고, 그
--   결과 관리자가 3명까지 늘어 있었다. 관리자는 화이트리스트 추가·삭제와 지식 지도
--   관리를 할 수 있으므로, 권한을 나눠 가질수록 실수로 남의 계정을 지울 경로만 늘어난다.
--   앞으로 일반 직원은 전부 동일한 권한을 갖고, 관리 작업은 00001 로 로그인해서 한다.
--   (체크박스는 UI 에서 제거했고, 등록 API 는 항상 is_admin=false 로 넣는다)
update employee_whitelist
  set is_admin = false
  where employee_id <> '00001';

comment on column employee_whitelist.is_admin is
  '관리자 계정 여부. 00001 한 계정에만 true 이며, 화면에서는 더 이상 부여할 수 없다.';
