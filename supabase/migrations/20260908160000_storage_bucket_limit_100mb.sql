-- 왜 필요한가
--   업로드 최대 용량을 50MB → 100MB 로 올렸다(lib/file-rules.ts). 앱만 고치면
--   앱의 검사는 통과하는데 스토리지가 거부해서, 사용자에게는 원인을 알 수 없는
--   업로드 실패로 보인다. 버킷 제한은 서명 URL을 직접 손에 넣은 경우까지 막는
--   마지막 방어선이므로 앱과 같은 값으로 맞춰 둔다
--   (20260905120000_storage_bucket.sql 의 설정 근거와 같은 이유다).
--
-- 무엇을 하는가
--   file-server 버킷의 file_size_limit 만 100MB 로 올린다.
--   public / allowed_mime_types 등 나머지 설정은 건드리지 않는다.
--
-- 100MB 로 정한 근거
--   저장공간보다 전송량이 먼저 바닥난다. 첨부는 /api/notes/{id}/content 가 바이트를
--   그대로 흘려보내므로 한 번 열 때마다 Supabase 와 Vercel 양쪽에서 파일 크기만큼
--   전송량이 발생한다. 300MB 를 허용하면 파일 하나를 여러 명이 한 번씩 열어보는 것만으로
--   월 전송량 한도에 닿는다. 큰 원본(PPT 등)은 앱에 올리는 대신 링크로 두기로 했다.
--
-- 주의
--   Supabase 무료 플랜은 파일 하나당 50MB 가 플랫폼 차원의 상한이라, 이 값을 올려도
--   실제 업로드는 50MB 에서 막힌다. 100MB 가 실제로 동작하려면 Pro 플랜이어야 한다.
update storage.buckets
   set file_size_limit = 104857600
 where id = 'file-server';
