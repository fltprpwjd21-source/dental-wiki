-- 첨부 상한을 100MB 에서 50MB 로 되돌린다 (2026-09-10)
--
-- 왜 되돌리나
--   20260908160000 에서 버킷을 100MB 로 올렸지만, Supabase 무료 플랜은 파일 하나당
--   50MB 가 플랫폼 차원의 상한이다. 버킷 값만 100MB 로 두면 앱은 통과시키고 스토리지가
--   거부해서, 사용자에게는 원인을 알 수 없는 업로드 실패로 보인다. 앱·버킷·플랫폼
--   세 값이 어긋난 상태를 만드느니 셋 다 50MB 로 맞춰 둔다.
--   (100MB 가 실제로 필요해지면 Pro 플랜으로 올린 뒤 다시 판단한다)
--
--   올렸던 마이그레이션 파일은 trash-can/ 으로 옮겼다. 이미 적용된 버전이라
--   기록(supabase_migrations)에는 남아 있으므로, 되돌리는 일은 이 새 마이그레이션이 한다.
--
-- 함께 바꾼 것
--   lib/file-rules.ts 의 FILE_MAX_SIZE_MB 기본값도 50 으로 되돌렸다. 한쪽만 고치면
--   같은 어긋남이 반대 방향으로 생긴다.
update storage.buckets
   set file_size_limit = 52428800
 where id = 'file-server';
