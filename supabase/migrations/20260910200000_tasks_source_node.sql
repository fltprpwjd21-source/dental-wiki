-- 업무지시에 보관함 자료를 연결한다 (2026-09-10)
--
-- 왜 필요한가
--   "이 폴더 정리해주세요", "이 노트 보고 따라 해주세요" 처럼 지시의 알맹이가 이미
--   보관함에 있는 경우가 많다. 지시문에 그 내용을 다시 옮겨 적으면 두 곳이 갈라지고,
--   어느 쪽이 최신인지 알 수 없게 된다. 원본은 보관함에 두고 여기서는 가리키기만 한다.
--   (공지가 notices.source_note_id 로 원본을 가리키는 것과 같은 방식이다)
--
-- 왜 nodes 를 가리키는가
--   보관함의 폴더·노트·첨부는 모두 nodes 한 표에 들어 있다(type 으로 갈린다).
--   그래서 폴더를 지시하든 노트를 지시하든 이 칸 하나로 된다.
--
-- 왜 외래키를 걸지 않는가
--   연결한 노트가 나중에 휴지통으로 가거나 완전 삭제될 수 있다. 외래키를 걸면 그때
--   보관함 정리가 업무지시 때문에 막히거나, cascade 로 지시가 통째로 사라진다.
--   둘 다 곤란하다 — 자료가 없어져도 "그때 이걸 시켰다"는 기록은 남아야 한다.
--   화면은 이 id 로 노트를 찾아보고, 없으면 「삭제된 자료」로 표시한다.
alter table tasks
  add column source_node_id uuid;

comment on column tasks.source_node_id is
  '지시와 함께 가리키는 보관함 항목(nodes.id). 폴더·노트 모두 가능하다. 외래키가 아니므로 원본이 사라질 수 있고, 그때 화면은 「삭제된 자료」로 표시한다.';
